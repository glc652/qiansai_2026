uint16_t Battery_ReadMillivolts(void)
{
  uint32_t raw;
  uint32_t pin_mv;
  uint32_t battery_mv;

  if (HAL_ADC_Start(&hadc1) != HAL_OK)
  {
    return 0U;
  }

  if (HAL_ADC_PollForConversion(&hadc1, 5U) != HAL_OK)
  {
    (void)HAL_ADC_Stop(&hadc1);
    return 0U;
  }

  raw = HAL_ADC_GetValue(&hadc1);
  (void)HAL_ADC_Stop(&hadc1);

  pin_mv = (raw * 3300U) / 4095U;
  battery_mv = pin_mv * 5U;
  if (battery_mv > 65535U)
  {
    battery_mv = 65535U;
  }

  return (uint16_t)battery_mv;
}

uint8_t Battery_ReadPercent(void)
{
  uint16_t mv = Battery_ReadMillivolts();
  uint32_t percent;

  if (mv == 0U)
  {
    return 0U;
  }
  if (mv <= 3400U)
  {
    return 0U;
  }
  if (mv >= 3900U)
  {
    return 100U;
  }

  percent = (((uint32_t)mv - 3400U) * 100U) / 500U;
  return (uint8_t)percent;
}

